def is_holdout(raw):
    return zlib.crc32(raw.encode('utf-8')) % 10 == 9

class ReviewGen:
    def __init__(self, seed):
        self.r = random.Random(seed)

    def _aspects(self, domain, tag):
        bank = DOMAIN[domain]
        w = {a: 1.0 for a in bank}
        w.update({a: 0.6 for a in COMMON})
        if domain == 'food':
            if tag == 'treat': w['활용'] = 2.0; w['성분'] = 0.6
            else: w['활용'] = 0.2; w['성분'] = 1.2
        if domain == 'device':
            if tag == 'bowl': w['소음'] = 0.1; w['기능'] = 0.2; w['사용성'] = 0.4
            if tag == 'filter': w['소음'] = 0.3; w['디자인'] = 0.3; w['기능'] = 1.6
        return w

    def _pick(self, w, n, exclude=()):
        keys = [k for k in w if k not in exclude]
        out = []
        for _ in range(min(n, len(keys))):
            k = self.r.choices(keys, [w[x] for x in keys])[0]
            out.append(k); keys.remove(k)
        return out

    def _bank(self, domain, aspect):
        return COMMON[aspect] if aspect in COMMON else DOMAIN[domain][aspect]

    def make(self, domain, sp, rating, delay_flag, incident, prod, brand, tag):
        R = self.r
        base = 'pos' if rating >= 4 else ('neu' if rating == 3 else 'neg')
        sent, mismatch = base, False
        if R.random() < 0.04:
            sent = {'pos': R.choices(['neu', 'neg'], [75, 25])[0], 'neu': R.choice(['pos', 'neg']), 'neg': R.choices(['neu', 'pos'], [75, 25])[0]}[base]
            mismatch = True
        slots = dict(pet='강아지' if sp == 'DOG' else '고양이', pn=R.choice(NAMES), dur=R.choice(DUR), ing=ingredient_of(prod), prod=prod, brand=brand)
        raws, parts, aspects = [], [], []
        def add(raw, prefix=''):
            raws.append(raw); parts.append(prefix + raw.format_map(slots))
        if R.random() < 0.10:
            raw = R.choice(SHORT[sent]); add(raw)
            text = self._style(parts[0], sent)
            return dict(text=text, label=LABEL_KO[sent], label_en=LABEL_EN[sent], aspects='', mismatch=mismatch, holdout=is_holdout(raw), n_clauses=1)
        w = self._aspects(domain, tag)
        items = []   # (aspect, pol, connector)
        if sent == 'pos':
            for a in self._pick(w, R.choice([1, 2, 2, 3])): items.append((a, '+', ''))
            if rating == 4 and R.random() < 0.35:
                a = self._pick(w, 1, exclude=[i[0] for i in items])
                if a: items.append((a[0], '-', R.choice(CONN['minor_neg'])))
        elif sent == 'neu':
            a = self._pick(w, 2)
            if len(a) == 2:
                if R.random() < 0.5: items = [(a[0], '+', ''), (a[1], '-', R.choice(CONN['contrast']))]
                else: items = [(a[0], '-', ''), (a[1], '+', R.choice(CONN['soft_pos']))]
            else: items = [(a[0], '-', '')]
        else:
            for a in self._pick(w, R.choice([1, 1, 2, 3])): items.append((a, '-', ''))
            if R.random() < 0.25:
                a = self._pick(w, 1, exclude=[i[0] for i in items])
                if a: items.append((a[0], '+', R.choice(CONN['soft_pos'])))
        if sent != 'pos' and delay_flag:
            items = [('배송', '-', '')] + [i for i in items if i[0] != '배송'][:1]
        if mention := (R.random() < 0.35): add(R.choice(MENTION[domain]))
        if R.random() < 0.35: add(R.choice(OPEN[sent]))
        inc_done = False
        if sent != 'pos' and incident:
            add(R.choice(INCIDENT)); aspects.append(('기능', '-')); inc_done = True
            items = items[:1] if not delay_flag else items
        for a, pol, conn in items:
            raw = R.choice(self._bank(domain, a)[0 if pol == '+' else 1])
            c = conn if conn.endswith(' ') or not conn else conn
            add(raw, prefix=c); aspects.append((a, pol))
        if len(parts) < 2: add(R.choice(OPEN[sent]))
        if R.random() < 0.45: add(R.choice(CLOSE[sent]))
        text = self._style(' '.join(parts), sent)
        return dict(text=text, label=LABEL_KO[sent], label_en=LABEL_EN[sent], aspects='|'.join(f'{a}:{p}' for a, p in aspects),
                    mismatch=mismatch, holdout=any(is_holdout(x) for x in raws), n_clauses=len(parts))

    def _style(self, t, sent):
        R = self.r
        if R.random() < 0.08:
            sp = [i for i, ch in enumerate(t) if ch == ' ']
            if sp: i = R.choice(sp); t = t[:i] + t[i + 1:]
        x = R.random()
        if x < 0.10: t += R.choice({'pos': [' ㅎㅎ', '^^', '!!'], 'neu': ['..', ' ㅎ'], 'neg': [' ㅠㅠ', '...', ' ㅜㅜ']}[sent])
        elif x < 0.13: t += R.choice({'pos': [' 👍', ' 😊'], 'neu': [' 🤔'], 'neg': [' 😢', ' 😡']}[sent])
        return t.strip()
