-- ============================================================
-- Pawcast DB 초기화 (DB 생성 + 전체 테이블 생성)
-- 실행: psql -U postgres -h localhost -f pawcast_init.sql
-- 기준: src.zip 엔티티(JPA/Hibernate 네이밍) + ERD
-- ============================================================
\set ON_ERROR_STOP on

-- 1) 기존 DB 전부 삭제 후 새로 생성 (접속 중인 세션은 강제 종료, 데이터 모두 삭제됨)
DROP DATABASE IF EXISTS powcast WITH (FORCE);
DROP DATABASE IF EXISTS pawcast WITH (FORCE);
CREATE DATABASE pawcast;

-- 2) 생성한 DB로 접속
\connect pawcast
-- 재접속하면 클라이언트 인코딩이 초기화되므로 접속 후에 지정
\encoding UTF8

-- 3) 테이블 생성 (FK 의존 순서)
BEGIN;

-- 회원
CREATE TABLE members (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             varchar(50)  UNIQUE,
    name                varchar(50)  NOT NULL,
    email               varchar(200) NOT NULL UNIQUE,
    tel                 varchar(50),
    password_hash       varchar(300),
    role                varchar(20)  NOT NULL DEFAULT 'USER'
                        CHECK (role IN ('GUEST','USER','MANAGER','ADMIN')),
    status              varchar(255) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE','INACTIVE','DELETED','KICKED')),
    is_agreed_terms     boolean      NOT NULL,
    is_agreed_privacy   boolean      NOT NULL,
    is_agreed_efinance  boolean      NOT NULL,
    is_agreed_marketing boolean      NOT NULL,
    deleted_at          timestamp(6),
    created_at          timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 이메일 인증
CREATE TABLE email_verification (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             varchar(200) NOT NULL,
    verification_code varchar(255) NOT NULL,
    expires_at        timestamp(6) NOT NULL,
    verified_at       timestamp(6),
    created_at        timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_email_verification_email ON email_verification (email);

-- 배송지
CREATE TABLE address (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint       NOT NULL REFERENCES members (id),
    label      varchar(50)  NOT NULL,
    recipient  varchar(50)  NOT NULL,
    tel        varchar(255),
    zipcode    varchar(5)   NOT NULL,
    address1   varchar(200) NOT NULL,
    address2   varchar(200) NOT NULL,
    is_default boolean      NOT NULL DEFAULT false
);

-- 리프레시 토큰
CREATE TABLE refresh_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint       NOT NULL REFERENCES members (id),
    token      varchar(1000) NOT NULL UNIQUE,
    expires_at timestamp(6) NOT NULL,
    revoked    boolean      NOT NULL DEFAULT false,
    user_agent varchar(300),
    ip_address varchar(45)
);

-- 소셜 계정 (ERD: 회원 1:N, (provider, provider_user_id) 유니크)
CREATE TABLE oauth_accounts (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        bigint       NOT NULL REFERENCES members (id),
    provider         varchar(255) NOT NULL,
    provider_user_id varchar(255) NOT NULL,
    created_at       timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_oauth_provider_user UNIQUE (provider, provider_user_id)
);

-- 카테고리 (자기참조)
CREATE TABLE categories (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      varchar(255) NOT NULL,
    parent_id bigint REFERENCES categories (id)
);

-- 상품
CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  bigint REFERENCES categories (id),
    name         varchar(200) NOT NULL,
    brand        varchar(100),
    product_type varchar(255) NOT NULL CHECK (product_type IN ('DOG','CAT','DEVICE')),
    description  text,
    sales_count  bigint       NOT NULL DEFAULT 0,
    wish_count   bigint       NOT NULL DEFAULT 0,
    review_count bigint       NOT NULL DEFAULT 0,
    rating_sum   bigint       NOT NULL DEFAULT 0,
    created_at   timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 사료 상세 (1:1)
CREATE TABLE food_details (
    product_id             bigint PRIMARY KEY REFERENCES products (id),
    food_kind              varchar(255),
    food_form              varchar(255),
    main_ingredient        varchar(255),
    life_stage             varchar(255),
    ingredient_description text
);

-- 기기 상세 (1:1)
CREATE TABLE device_details (
    product_id          bigint PRIMARY KEY REFERENCES products (id),
    device_kind         varchar(255) NOT NULL,
    material            varchar(255),
    feature_description text
);

-- 상품 옵션(SKU)
CREATE TABLE product_variants (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id             bigint         NOT NULL REFERENCES products (id),
    sku_code               varchar(255)   NOT NULL UNIQUE,
    option_key             varchar(150)   NOT NULL,
    option_label           varchar(150)   NOT NULL,
    color                  varchar(50),
    weight_g               integer,
    volume_ml              integer,
    capacity_ml            integer,
    height_cm              integer,
    price                  numeric(38,2)  NOT NULL,
    cost_price             numeric(38,2)  NOT NULL,
    stock                  integer        NOT NULL DEFAULT 0,
    product_variant_status varchar(255)   NOT NULL
                           CHECK (product_variant_status IN ('ON_SALE','SOLD_OUT','DISCONTINUED')),
    sales_count            bigint         NOT NULL DEFAULT 0,
    created_at             timestamp(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             timestamp(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 상품 이미지
CREATE TABLE product_images (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint       NOT NULL REFERENCES products (id),
    image_path varchar(255) NOT NULL,
    is_main    boolean      NOT NULL DEFAULT false,
    sort_order integer      NOT NULL DEFAULT 0,
    created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 반려동물
CREATE TABLE pets (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint        NOT NULL REFERENCES members (id),
    name       varchar(20)   NOT NULL,
    pet_type   varchar(255)  NOT NULL CHECK (pet_type IN ('CAT','DOG')),
    birthday   date,
    breed_name varchar(50),
    weight_kg  numeric(38,2),
    allergies  text,
    life_stage varchar(255),
    created_at timestamp(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 반려동물 추천
CREATE TABLE pet_recommendations (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id              bigint       NOT NULL REFERENCES pets (id),
    product_id          bigint       NOT NULL REFERENCES products (id),
    recommendation_rank integer      NOT NULL,
    created_at          timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 찜
CREATE TABLE wishlists (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint       NOT NULL REFERENCES members (id),
    product_id bigint       NOT NULL REFERENCES products (id),
    created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 장바구니
CREATE TABLE carts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint       NOT NULL REFERENCES members (id),
    status     varchar(255) NOT NULL CHECK (status IN ('ACTIVE','ORDERED')),
    created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cart_items (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    bigint  NOT NULL REFERENCES carts (id),
    variant_id bigint  NOT NULL REFERENCES product_variants (id),
    quantity   integer NOT NULL,
    CONSTRAINT uq_cart_items_cart_variant UNIQUE (cart_id, variant_id)
);

-- 주문
CREATE TABLE orders (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         bigint REFERENCES members (id),
    order_number      varchar(22)   NOT NULL UNIQUE,
    status            varchar(255)  NOT NULL
                      CHECK (status IN ('PENDING_PAYMENT','PAID','PREPARING','SHIPPING','DELIVERED','CANCELLED')),
    total_amount      numeric(12,0) NOT NULL,
    discount_amount   numeric(12,0) NOT NULL DEFAULT 0,
    shipping_fee      numeric(12,0) NOT NULL DEFAULT 0,
    final_amount      numeric(12,0) NOT NULL,
    recipient_name    varchar(50)   NOT NULL,
    recipient_phone   varchar(20),
    recipient_email   varchar(100)  NOT NULL,
    delivery_zipcode  varchar(5)    NOT NULL,
    delivery_address1 varchar(255)  NOT NULL,
    delivery_address2 varchar(255),
    delivery_message  varchar(255),
    created_at        timestamp(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at        timestamp(6)
);

CREATE TABLE order_items (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           bigint        NOT NULL REFERENCES orders (id),
    product_variant_id bigint        NOT NULL REFERENCES product_variants (id),
    product_name       varchar(50)   NOT NULL,
    option_label       varchar(50)   NOT NULL,
    quantity           integer       NOT NULL DEFAULT 1,
    unit_price         numeric(12,0) NOT NULL,
    total_price        numeric(12,0) NOT NULL
);

-- 결제 (주문 1:1)
CREATE TABLE payments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint        NOT NULL UNIQUE REFERENCES orders (id),
    payment_method  varchar(255)  NOT NULL
                    CHECK (payment_method IN ('CARD','BANK','VIRTUAL_ACCOUNT','EASY_PAY')),
    provider        varchar(50)   NOT NULL,
    payment_key     varchar(255),
    idempotency_key varchar(100)  NOT NULL UNIQUE,
    amount          numeric(12,0) NOT NULL,
    status          varchar(255)  NOT NULL
                    CHECK (status IN ('PENDING','PAID','CANCELLED','FAILED')),
    paid_at         timestamp(6),
    created_at      timestamp(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 환불 (결제 1:1)
CREATE TABLE refunds (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          bigint        NOT NULL UNIQUE REFERENCES payments (id),
    provider_refund_key varchar(255),
    idempotency_key     varchar(255)  NOT NULL UNIQUE,
    refund_amount       numeric(38,2) NOT NULL,
    reason              varchar(255)  NOT NULL,
    status              varchar(255)  NOT NULL CHECK (status IN ('PENDING','COMPLETED','FAILED')),
    created_at          timestamp(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at        timestamp(6)
);

-- 리뷰
CREATE TABLE product_reviews (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     bigint       NOT NULL REFERENCES members (id),
    product_id    bigint       NOT NULL REFERENCES products (id),
    order_item_id bigint       NOT NULL UNIQUE REFERENCES order_items (id),
    rating        integer      NOT NULL,
    content       text         NOT NULL,
    is_visible    boolean      NOT NULL DEFAULT true,
    created_at    timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE review_images (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id  bigint       NOT NULL REFERENCES product_reviews (id),
    image_path varchar(255) NOT NULL,
    sort_order integer      NOT NULL DEFAULT 0
);

CREATE TABLE review_sentiments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   bigint NOT NULL UNIQUE REFERENCES product_reviews (id),
    sentiment   varchar(255),
    confidence  numeric(38,2),
    model_name  varchar(255),
    analyzed_at timestamp(6)
);

-- 공지사항
CREATE TABLE notices (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   bigint       NOT NULL REFERENCES members (id),
    notice_type varchar(255) NOT NULL DEFAULT 'GENERAL' CHECK (notice_type IN ('GENERAL','EVENT')),
    title       varchar(100) NOT NULL,
    content     text         NOT NULL,
    is_pinned   boolean      NOT NULL DEFAULT false,
    deleted_at  timestamp(6),
    created_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 문의 (상품/일반)
CREATE TABLE qnas (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint       NOT NULL REFERENCES members (id),
    product_id bigint       REFERENCES products (id),
    type       varchar(255) NOT NULL DEFAULT 'GENERAL' CHECK (type IN ('PRODUCT','GENERAL')),
    title      varchar(100) NOT NULL,
    content    text         NOT NULL,
    is_private boolean      NOT NULL DEFAULT false,
    deleted_at timestamp(6),
    created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 문의 답변 (문의당 1개)
CREATE TABLE qna_answers (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qna_id     bigint       NOT NULL UNIQUE REFERENCES qnas (id),
    member_id  bigint       REFERENCES members (id),
    content    text         NOT NULL,
    created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 상품-대상 반려동물 (N:M 매핑)
-- ※ ERD에 컬럼 미정의 → (product_id, pet_type) 복합 PK로 가정
CREATE TABLE product_pet_types (
    product_id bigint       NOT NULL REFERENCES products (id),
    pet_type   varchar(255) NOT NULL CHECK (pet_type IN ('CAT','DOG')),
    PRIMARY KEY (product_id, pet_type)
);

-- 재고 이력 (ERD 기준)
CREATE TABLE inventory_transactions (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id       bigint       NOT NULL REFERENCES product_variants (id),
    member_id        bigint       REFERENCES members (id),  -- 처리자, 시스템 처리 시 NULL
    transaction_type varchar(255) NOT NULL,                  -- 입고, 출고, 조정 등
    quantity_change  integer      NOT NULL,
    stock_before     integer      NOT NULL,
    stock_after      integer      NOT NULL,
    reference_type   varchar(255),                           -- 주문 등
    created_at       timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_inventory_variant ON inventory_transactions (variant_id);

-- 배송 (주문 1:1, ERD 기준)
CREATE TABLE shipments (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              bigint       NOT NULL UNIQUE REFERENCES orders (id),
    delivery_api_provider varchar(255),
    external_shipment_id  varchar(255),
    carrier_code          varchar(255),
    tracking_number       varchar(255),
    status                varchar(255),
    last_event_at         timestamp(6) with time zone,
    last_synced_at        timestamp(6) with time zone,
    shipped_at            timestamp(6) with time zone,
    delivered_at          timestamp(6) with time zone
);

-- 자주 쓰는 조회용 인덱스
CREATE INDEX idx_products_category      ON products (category_id);
CREATE INDEX idx_variants_product       ON product_variants (product_id);
CREATE INDEX idx_orders_member          ON orders (member_id);
CREATE INDEX idx_order_items_order      ON order_items (order_id);
CREATE INDEX idx_reviews_product        ON product_reviews (product_id);
CREATE INDEX idx_wishlists_member       ON wishlists (member_id);
CREATE INDEX idx_pets_member            ON pets (member_id);

COMMIT;

-- 결과 확인
\dt
